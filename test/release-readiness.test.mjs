// Public launch readiness checks for docs, release scripts, and GitHub hygiene.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, readFileSync, statSync } from 'node:fs';

function read(rel) {
  return readFileSync(new URL(`../${rel}`, import.meta.url), 'utf8');
}

function exists(rel) {
  return existsSync(new URL(`../${rel}`, import.meta.url));
}

test('README leads with a visual demo, desktop quickstart, and local-first positioning', () => {
  const readme = read('README.md');
  assert.match(readme, /!\[codeStory saved stories screen\]\(assets\/demo\/codestory-story-picker\.png\)/);
  assert.match(readme, /!\[codeStory guided review screen\]\(assets\/demo\/codestory-review\.png\)/);
  assert.match(readme, /!\[codeStory concept primer with a diagram\]\(assets\/demo\/codestory-concept\.png\)/);
  assert.doesNotMatch(readme, /assets\/demo\/codestory-demo\.svg/);
  assert.match(readme, /scripts\/install-macos-app\.sh/);
  assert.match(readme, /There is no\s+codeStory CLI/);
  assert.match(readme, /Works without AI/);
  assert.match(readme, /No Python is required for the core app\./);
});

test('package exposes release checks and ships demo and browser assets with npm package', () => {
  const pkg = JSON.parse(read('package.json'));
  assert.match(pkg.scripts.build, /npm run build:browser-assets/);
  assert.equal(pkg.scripts['build:browser-assets'], 'node scripts/build-browser-assets.mjs');
  assert.equal(pkg.scripts.dev, 'npm run build && node dist/app-server.js');
  assert.equal(pkg.bin, undefined);
  assert.equal(pkg.scripts.check, 'npm run build && npm run typecheck:client && node --test test/*.test.mjs');
  assert.equal(pkg.scripts['test:browser'], 'npm run build && node scripts/browser-smoke.mjs');
  assert.equal(pkg.scripts['release:check'], 'npm run check && npm pack --dry-run --json');
  assert.equal(pkg.scripts.prepublishOnly, 'npm run check');
  assert.equal(pkg.license, 'SEE LICENSE IN LICENSE');
  assert.ok(pkg.files.includes('dist'));
  assert.ok(pkg.files.includes('assets/demo'));
});

test('codeStory is UI-only and distributed skills never direct users to a CLI', () => {
  const pkg = JSON.parse(read('package.json'));
  const readme = read('README.md');
  const storyteller = read('skills/codestory-storyteller/SKILL.md');

  assert.equal(pkg.bin, undefined);
  assert.equal(exists('src/cli.ts'), false);
  assert.equal(exists('dist/cli.js'), false);
  assert.equal(exists('scripts/install.sh'), false);
  assert.doesNotMatch(readme, /npm i -g @naveedinno\/codestory/);
  assert.match(storyteller, /codeStory is UI-only/);
  assert.equal(exists('skills/address-review/SKILL.md'), false);
  assert.doesNotMatch(storyteller, /codestory check|codestory --/);
  // The bundled checker ships inside the skill folder and is run with node;
  // it is not an installed CLI and has no package alias.
  const checker = read('skills/codestory-storyteller/scripts/check-story.mjs');
  assert.ok(checker.startsWith('#!/usr/bin/env node\n// GENERATED by scripts/build-skill-checker.mjs'));
  assert.doesNotMatch(read('package.json'), /check-story/);
});

test('release build contains a self-contained Mermaid ESM browser bundle', () => {
  const buildScript = read('scripts/build-browser-assets.mjs');
  assert.match(buildScript, /mermaid\/dist\/mermaid\.esm\.min\.mjs/);
  assert.match(buildScript, /format: 'esm'/);
  assert.match(buildScript, /platform: 'browser'/);
  assert.match(buildScript, /minify: true/);
  assert.match(buildScript, /legalComments: 'eof'/);

  const asset = 'dist/mermaid.esm.min.mjs';
  assert.ok(exists(asset), `${asset} should be generated before packaging`);
  assert.ok(statSync(new URL(`../${asset}`, import.meta.url)).size > 500_000, `${asset} should contain Mermaid, not a loader stub`);
  const source = read(asset);
  assert.match(source, /export\{/);
  assert.match(source, /\/\*!|@license|@preserve/);
});

