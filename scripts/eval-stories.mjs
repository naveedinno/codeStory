function judgePrompt(c, storyJson, diff) {
  const truncated = diff.length > 60000 ? `${diff.slice(0, 60000)}\n[diff truncated at 60000 chars]` : diff;
  return [
    'You are grading a "codeStory": a guided review story an AI wrote for its own code change. Grade like a demanding staff reviewer: 3 is adequate, 5 is rare.',
    '',
    `Rubric (score each 1-5):`,
    ...RUBRIC.map(([k, d]) => `- ${k}: ${d}`),
    '',
    'Reply with STRICT JSON only, no markdown fences, exactly this shape:',
    '{"scores":{' + RUBRIC.map(([k]) => `"${k}":0`).join(',') + '},"rationale":{' + RUBRIC.map(([k]) => `"${k}":"one sentence"`).join(',') + '},"worstStep":"<step id and why>","verdict":"<one sentence: would this story actually help a reviewer?>"}',
    '',
    `Change note: ${c.note}`,
    '',
    '--- STORY JSON ---',
    storyJson,
    '',
    '--- THE ACTUAL DIFF ---',
    truncated,
  ].join('\n');
}

function parseJudgeOutput(raw) {
  const start = raw.indexOf('{');
  const end = raw.lastIndexOf('}');
  if (start === -1 || end <= start) throw new Error('judge returned no JSON object');
  return JSON.parse(raw.slice(start, end + 1));
}

async function judge(c) {
  const caseDir = join(outDir, c.id);
  const storyFile = join(caseDir, 'story.json');
  if (!existsSync(storyFile)) {
    console.log(`\n▶ judge ${c.id} — no story.json (generate first), skipping`);
    return null;
  }
  console.log(`\n▶ judge ${c.id} (model ${judgeLabel})`);
  const storyJson = readFileSync(storyFile, 'utf8');
  const tour = JSON.parse(storyJson);
  const mechanical = mechanicalScores(c, tour);
  const gateErrors = mechanical.validationErrors.length + mechanical.generatedProfileErrors.length;
  // Mechanical scores are instant, so show them before the slow judge call.
  const { tables, signalSpans } = mechanical.markupUse;
  console.log(
    `  ${mechanical.steps} steps · ${mechanical.hotspots} hotspots · ` +
    `${mechanical.uncoveredHunks} uncovered ${mechanical.uncoveredHunks === 1 ? 'hunk' : 'hunks'} · ` +
    `${gateErrors} validation ${gateErrors === 1 ? 'error' : 'errors'}` +
    (tables || signalSpans ? ` · ${tables} ${tables === 1 ? 'table' : 'tables'}, ${signalSpans} signal spans` : ''),
  );
  if (mechanical.lint) {
    const top = Object.entries(mechanical.lint.byRule).sort((x, y) => y[1] - x[1]).slice(0, 4);
    console.log(
      `  lint: ${mechanical.lint.errors} errors, ${mechanical.lint.warnings} warnings` +
      (top.length ? ` (${top.map(([rule, n]) => `${rule} x${n}`).join(', ')})` : ''),
    );
  }
  // Loud, because it is invisible everywhere else: this story validates clean and
  // then shows its asterisks to the reviewer.
  if (mechanical.markdownResidue.length) {
    console.log(`  ⚠ Markdown left in ${mechanical.markdownResidue.length} narrative field(s) — renders literally:`);
    for (const hit of mechanical.markdownResidue.slice(0, 5)) console.log(`      ${hit}`);
    if (mechanical.markdownResidue.length > 5) console.log(`      … and ${mechanical.markdownResidue.length - 5} more`);
  }
  const judgeOpts = { logPath: join(caseDir, 'judge.log'), activity: 'grading' };
  const { out, took } = runner === 'muse'
    ? await runMuse({ prompt: judgePrompt(c, storyJson, caseDiff(c)), cwd: root, ...judgeOpts })
    : await runClaude({
        cliArgs: ['-p', judgePrompt(c, storyJson, caseDiff(c)), '--model', judgeModel],
        ...judgeOpts,
      });
  const llm = parseJudgeOutput(out);
  const mean = Object.values(llm.scores).reduce((a, b) => a + b, 0) / RUBRIC.length;
  const result = { case: c.id, mode: c.mode, mechanical, llm, mean: Number(mean.toFixed(2)) };
  writeFileSync(join(caseDir, 'judge.json'), JSON.stringify(result, null, 2));
  console.log(`  ✓ mean ${result.mean} in ${took} — ${truncate(llm.verdict)}`);
  return result;
}

/** Blind A/B prompt. Order is swapped on the second call to cancel position bias. */
function comparePrompt(c, first, second, diff) {
  const truncated = diff.length > 60000 ? `${diff.slice(0, 60000)}\n[diff truncated at 60000 chars]` : diff;
  return [
    'Two AI-written "codeStory" review stories explain the SAME code change. Pick the one that would help a reviewer who knows the goal but not this code understand the change and find its risks faster.',
    'Weigh: landing (each step says where we are and who calls it before what changed), rationale (why this and not the obvious alternative), concreteness, risk calibration (honest, specific doubts), listenability (it is read aloud), and truth to the diff.',
    'Do NOT prefer a story for being longer or more detailed; prefer the one a reviewer would rather follow. A story that invents behavior the diff does not show loses.',
    '',
    'Reply with STRICT JSON only, no markdown fences: {"winner":"A"|"B"|"tie","why":"one sentence","landing":"A|B|tie","rationale":"A|B|tie","listenability":"A|B|tie"}',
    '',
    `Change note: ${c.note}`,
    '',
    '--- STORY A ---',
    first,
    '',
    '--- STORY B ---',
    second,
    '',
    '--- THE ACTUAL DIFF ---',
    truncated,
  ].join('\n');
}

async function compareCase(c, labelA, labelB) {
  const read = (l) => {
    const file = join(root, 'eval', 'results', l, c.id, 'story.json');
    return existsSync(file) ? readFileSync(file, 'utf8') : null;
  };
  const a = read(labelA);
  const b = read(labelB);
  if (!a || !b) {
    console.log(`\n▶ compare ${c.id} — missing a story (${!a ? labelA : labelB}), skipping`);
    return null;
  }
  const dir = join(root, 'eval', 'results', `compare-${labelA}-vs-${labelB}`, c.id);
  mkdirSync(dir, { recursive: true });
  const diff = caseDiff(c);
  console.log(`\n▶ compare ${c.id}: ${labelA} vs ${labelB} (both orders, model ${judgeLabel})`);
  const ask = async (first, second, log) => {
    const prompt = comparePrompt(c, first, second, diff);
    const answered = runner === 'muse'
      ? await runMuse({ prompt, cwd: root, logPath: join(dir, log), activity: 'comparing' })
      : await runClaude({
          cliArgs: ['-p', prompt, '--model', judgeModel],
          logPath: join(dir, log),
          activity: 'comparing',
        });
    return parseJudgeOutput(answered.out);
  };
  const forward = await ask(a, b, 'a-first.log');
  const backward = await ask(b, a, 'b-first.log');
  const vote = (r, aFirst) => (r.winner === 'tie' ? 'tie' : (r.winner === 'A') === aFirst ? labelA : labelB);
  const votes = [vote(forward, true), vote(backward, false)];
  const result = { case: c.id, votes, agreed: votes[0] === votes[1] ? votes[0] : 'split', why: [forward.why, backward.why] };
  writeFileSync(join(dir, 'compare.json'), JSON.stringify(result, null, 2));
  console.log(`  ✓ ${result.agreed === 'split' ? `split (${votes.join(' / ')})` : `prefers ${result.agreed}`}`);
  return result;
}

function compareReport(results, labelA, labelB) {
  const done = results.filter(Boolean);
  const count = (who) => done.filter((r) => r.agreed === who).length;
  const md = [
    `# Blind comparison — ${labelA} vs ${labelB}`,
    '',
    `Judge: ${judgeLabel}. Each case is judged twice with the story order swapped; only agreeing votes count.`,
    '',
    `**${labelB}** preferred in ${count(labelB)}, **${labelA}** in ${count(labelA)}, tie in ${count('tie')}, split in ${count('split')} of ${done.length} cases.`,
    '',
    '| case | A-first vote | B-first vote | agreed |',
    '| --- | --- | --- | --- |',
    ...done.map((r) => `| ${r.case} | ${r.votes[0]} | ${r.votes[1]} | ${r.agreed} |`),
    '',
    ...done.map((r) => `## ${r.case}\n\n- A first: ${r.why[0]}\n- B first: ${r.why[1]}\n`),
  ].join('\n');
  const out = join(root, 'eval', 'results', `compare-${labelA}-vs-${labelB}`, 'report.md');
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, md);
  console.log(`\n${labelB} preferred in ${count(labelB)} of ${done.length} cases. Report: ${out}`);
}

function report(results) {
  const done = results.filter(Boolean);
  if (!done.length) return;
  const header = [
    'case', 'mode', 'mean', ...RUBRIC.map(([k]) => k),
    'val errors', 'md residue', 'lint E', 'lint W', 'uncovered', 'steps', 'hotspots', 'tables',
  ];
  const rows = done.map((r) => [
    r.case, r.mode, r.mean,
    ...RUBRIC.map(([k]) => r.llm.scores[k]),
    r.mechanical.validationErrors.length + r.mechanical.generatedProfileErrors.length,
    // Non-zero means the generator is still writing Markdown into HTML fields.
    r.mechanical.markdownResidue?.length ?? 0,
    r.mechanical.lint?.errors ?? '-',
    r.mechanical.lint?.warnings ?? '-',
    r.mechanical.uncoveredHunks, r.mechanical.steps, r.mechanical.hotspots,
    r.mechanical.markupUse?.tables ?? 0,
  ]);
  const md = [
    `# Story eval — ${label}`,
    '',
    `Generated ${new Date().toISOString()} · runner: ${runner} · generator: ${genLabel} · judge: ${judgeLabel}`,
    '',
    `| ${header.join(' | ')} |`,
    `| ${header.map(() => '---').join(' | ')} |`,
    ...rows.map((r) => `| ${r.join(' | ')} |`),
    '',
    ...done.map((r) => `## ${r.case}\n\n- verdict: ${r.llm.verdict}\n- worst step: ${r.llm.worstStep}\n- lint: ${r.mechanical.lint ? `${r.mechanical.lint.errors} errors, ${r.mechanical.lint.warnings} warnings ${JSON.stringify(r.mechanical.lint.byRule)}` : 'skipped (story failed basic validation)'}\n${RUBRIC.map(([k]) => `- ${k} (${r.llm.scores[k]}): ${r.llm.rationale[k]}`).join('\n')}\n`),
  ].join('\n');
  writeFileSync(join(outDir, 'report.md'), md);
  console.log(`\nOverall mean: ${(done.reduce((a, r) => a + r.mean, 0) / done.length).toFixed(2)} across ${done.length} cases`);
  console.log(`Report: eval/results/${label}/report.md`);
}

// Only run when invoked as a script — importing this file (e.g. from a test of
// progressLine) must not spawn billed agent runs.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  if (!['generate', 'judge', 'all', 'compare'].includes(command)) {
    console.error(`Unknown command "${command}". Use: generate | judge | all | compare`);
    process.exit(1);
  }
  if (!['claude', 'muse'].includes(runner)) {
    console.error(`Unknown runner "${runner}". Use: --runner claude | muse`);
    process.exit(1);
  }
  if (!onPath(runner)) {
    console.error(`The ${runner} CLI is required on PATH for generation and judging.`);
    process.exit(1);
  }
  if (command === 'compare') {
    const labelA = flag('a');
    const labelB = flag('b');
    if (!labelA || !labelB) {
      console.error('compare needs --a <label> --b <label>: two existing result labels under eval/results/.');
      process.exit(1);
    }
    const results = [];
    for (const c of selected) results.push(await compareCase(c, labelA, labelB));
    compareReport(results, labelA, labelB);
    console.log(`\nDone in ${elapsed()}.`);
    process.exit(0);
  }
  if (command !== 'judge') checkInstalledSkill();
  recoverStrandedStory();
  mkdirSync(outDir, { recursive: true });

  const plan = [command === 'all' ? 'generate + judge' : command, `${selected.length} case${selected.length === 1 ? '' : 's'}`];
  console.log(`\ncodeStory eval · ${plan.join(' · ')} · label "${label}"`);
  console.log(`Cases: ${selected.map((c) => c.id).join(', ')}`);
  for (const c of unavailable) console.log(`Skipping ${c.id}: ${c.repo} is not on this machine.`);
  if (command !== 'judge') {
    const runs = selected.length * (command === 'all' ? 2 : 1);
    console.log(`Spawning ${runs} billed ${runner} runs; each generation takes minutes. Ctrl-C to stop safely.`);
  }

  if (command === 'generate' || command === 'all') {
    // One case failing must never abort the run: the surviving stories are still
    // worth judging, and an escaping rejection would also strand the worktrees.
    const failures = [];
    const attempt = async (c, opts) => {
      try {
        await generate(c, opts);
      } catch (e) {
        failures.push({ id: c.id, message: e.message });
        console.log(`  ✖ ${c.id} failed: ${e.message}`);
      }
    };

    // Every generation runs in its own worktree, so a run never touches the live
    // repo and you can keep working (or run the tests) while it goes.
    const lanes = Math.min(parallel, selected.length);
    console.log(
      `Running ${lanes > 1 ? `${lanes} generations at a time` : 'one generation at a time'} ` +
      `in isolated git worktrees; your working tree is untouched.`,
    );
    const trees = makeWorktrees(selected);
    try {
      const queue = [...selected];
      const worker = async () => {
        for (let c = queue.shift(); c; c = queue.shift()) {
          // Quiet only when lanes would interleave and shred each other's lines.
          await attempt(c, { worktree: trees.get(c.id), quiet: lanes > 1 });
        }
      };
      await Promise.all(Array.from({ length: lanes }, worker));
    } finally {
      for (const tree of trees.values()) tree.cleanup();
    }

    if (failures.length) {
      console.log(`\n${failures.length} of ${selected.length} generations failed:`);
      for (const f of failures) console.log(`  ✖ ${f.id}: ${f.message}`);
      console.log('Judging continues on the stories that did succeed.');
    }
  }
  if (command === 'judge' || command === 'all') {
    const results = [];
    for (const c of selected) results.push(await judge(c));
    report(results);
  }
  console.log(`\nDone in ${elapsed()}.`);
}
