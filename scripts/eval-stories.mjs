#!/usr/bin/env node
// Story-quality eval harness: generate diffStories for frozen commit ranges,
// score them mechanically (the app's own validators + coverage gate), then with
// an LLM judge rubric derived from the storyteller skill's audits. This makes
// prompt/skill changes measurable instead of vibes.
//
//   node scripts/eval-stories.mjs all --label baseline
//   node scripts/eval-stories.mjs generate --label exp1 --case bugfix-review-ui
//   node scripts/eval-stories.mjs judge --label exp1
//   node scripts/eval-stories.mjs compare --a baseline --b after   # blind A/B, both orders
//   ... --runner muse   # spend the runs on the muse CLI instead of claude
//
// Requires: `npm run build` first (uses dist/), the `claude` CLI on PATH, and
// the codestory-storyteller skill installed (scripts/install-skills.sh).
// Results land in eval/results/<label>/ (gitignored).

import { spawn, spawnSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { homedir } from 'node:os';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { storyPrompt, streamCommand, parseClaudeStreamLine, onPath } from '../dist/agent.js';
import { validateTour, validateNewGeneratedStory } from '../dist/tour.js';
import { parseUnifiedDiff } from '../dist/diff.js';
import { computeCoverage, filesForStoryCoverage } from '../dist/coverage.js';
import { lintStory, MARKDOWN_RESIDUE } from '../dist/story-lint.js';
import { commitEvolutionManifest } from '../dist/git.js';
import { normalizeEvolutionObject } from '../dist/evolution.js';
import { skillDirDigest } from '../dist/repo-setup.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const storyPath = join(root, '.codestory', 'story.json');
const backupPath = `${storyPath}.eval-backup`;

const args = process.argv.slice(2);
const command = args[0] && !args[0].startsWith('--') ? args[0] : 'all';
const flag = (name, fallback) => {
  const i = args.indexOf(`--${name}`);
  return i !== -1 && args[i + 1] ? args[i + 1] : fallback;
};
const label = flag('label', 'baseline');
const genModel = flag('model', 'sonnet');
const judgeModel = flag('judge-model', 'sonnet');
// Which agent CLI spends the billed runs. Pinned per run, never mixed: a label
// generated by one runner and judged by another would not be comparable.
// Muse model pinned so a later default change fails loudly instead of silently
// measuring a different model (021 and 025 must use the same runner + model).
const runner = flag('runner', 'claude');
const MUSE_MODEL = 'muse-spark-1.3-contributor';
const genLabel = runner === 'muse' ? MUSE_MODEL : genModel;
const judgeLabel = runner === 'muse' ? MUSE_MODEL : judgeModel;
const onlyCases = args.flatMap((a, i) => (a === '--case' && args[i + 1] ? [args[i + 1]] : []));
const parallel = Math.max(1, Number(flag('parallel', '1')) || 1);
// Wall-clock cap per generation; 0 disables. Guards against a wedged agent.
// Generous by default: a large diff legitimately takes 15-25 minutes, and
// concurrency slows each run further, so a tight cap kills healthy agents
// mid-write rather than catching stuck ones.
const timeoutMs = Math.max(0, Number(flag('timeout', '40')) || 0) * 60000;

const { cases } = JSON.parse(readFileSync(join(root, 'eval', 'cases.json'), 'utf8'));
const requested = onlyCases.length ? cases.filter((c) => onlyCases.includes(c.id)) : cases;
// External-repo cases only run on machines that have that repo.
const unavailable = requested.filter((c) => c.repo && !existsSync(caseRepo(c)));
const selected = requested.filter((c) => !unavailable.includes(c));
if (!selected.length) {
  const skipped = unavailable.length ? ` (skipped for a missing repo: ${unavailable.map((c) => c.id).join(', ')})` : '';
  console.error(`No runnable cases match ${onlyCases.join(', ') || 'the case list'}${skipped}. Known: ${cases.map((c) => c.id).join(', ')}`);
  process.exit(1);
}
const outDir = join(root, 'eval', 'results', label);

/**
 * The agent loads the *installed* skill, not this repo's copy. A stale install
 * silently measures the old skill and makes every label comparison a lie, so
 * refuse to spend agent runs until the two match.
 */
export function skillInstallState(repoSkill, installedSkill) {
  if (installedSkill === null) return { ok: false, reason: 'not installed' };
  return installedSkill.trim() === repoSkill.trim()
    ? { ok: true }
    : { ok: false, reason: 'out of date' };
}

function checkInstalledSkill() {
  const repoDir = join(root, 'skills', 'codestory-storyteller');
  // Each runner reads its own directory: Muse loads the .agents copy.
  const target = runner === 'muse'
    ? join(process.env.HOME ?? '', '.agents', 'skills', 'codestory-storyteller')
    : join(process.env.HOME ?? '', '.claude', 'skills', 'codestory-storyteller');
  const installed = existsSync(join(target, 'SKILL.md')) ? skillDirDigest(target) : null;
  const state = skillInstallState(skillDirDigest(repoDir), installed);
  if (state.ok) return;
  const fix = runner === 'muse' ? 'sh scripts/install-skills.sh' : 'sh scripts/install-skills.sh --claude';
  console.error(
    `\n✖ The installed codestory-storyteller skill is ${state.reason}:\n` +
    `    ${target}\n` +
    `  The agent reads that copy (SKILL.md, references/, scripts/), so this run would score the wrong skill.\n` +
    `  Fix it first:  ${fix}\n`,
  );
  process.exit(1);
}

/** The repository a case's refs live in: this repo unless the case names another. */
export function caseRepo(c) {
  if (!c.repo) return root;
  return c.repo.startsWith('~/') ? join(homedir(), c.repo.slice(2)) : c.repo;
}

function gitIn(cwd, ...gitArgs) {
  const r = spawnSync('git', gitArgs, { cwd, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
  if (r.status !== 0) throw new Error(`git ${gitArgs.join(' ')} failed: ${r.stderr}`);
  return r.stdout;
}

function git(...gitArgs) {
  return gitIn(root, ...gitArgs);
}

function caseDiff(c) {
  return gitIn(caseRepo(c), 'diff', `${c.base}..${c.head}`, '--', ...(c.excludePaths ?? []).map((p) => `:(exclude)${p}`));
}

const startedAt = Date.now();
const elapsed = (since = startedAt) => {
  const s = Math.round((Date.now() - since) / 1000);
  return `${Math.floor(s / 60)}:${String(s % 60).padStart(2, '0')}`;
};

function truncate(text, max = (process.stdout.columns || 100) - 12) {
  const oneLine = String(text).replace(/\s+/g, ' ').trim();
  return oneLine.length > max ? `${oneLine.slice(0, max - 1)}…` : oneLine;
}

/**
 * How many API retries the CLI burned before giving up, or 0 if it did not.
 * The stream carries `{type:"system",subtype:"api_retry",attempt,max_retries}`;
 * reaching max_retries means the run died of infrastructure, not of anything
 * the story or the prompt did. Returns the attempt count so the caller can say
 * so plainly instead of reporting a bare non-zero exit.
 */
export function retriesExhausted(streamOutput) {
  let exhausted = 0;
  for (const line of String(streamOutput).split('\n')) {
    if (!line.startsWith('{') || !line.includes('api_retry')) continue;
    try {
      const event = JSON.parse(line);
      if (event.subtype === 'api_retry' && event.attempt && event.attempt >= event.max_retries) {
        exhausted = event.attempt;
      }
    } catch { /* a partial line is not a retry record */ }
  }
  return exhausted;
}

/**
 * One console line per real agent event. Returns null for events not worth a
 * line so the run stays readable — the full stream is always in the log file.
 * Phase markers (">> ...", the live-progress protocol the story prompt asks
 * for) are the story-shaped signal, so they get the arrow and stay unabridged.
 */
export function progressLine(event) {
  switch (event.type) {
    case 'file':
      return `${event.action} ${event.target}`;
    case 'command':
      return `$ ${event.command}`;
    case 'activity':
      return event.label;
    case 'tool':
      return event.label ?? event.rawTool;
    case 'plan':
      return `plan: ${event.items.filter((i) => i.status === 'active').map((i) => i.text).join(', ') || `${event.items.length} steps`}`;
    case 'text': {
      const marker = String(event.data).split('\n').map((l) => l.trim()).filter((l) => l.startsWith('>> '));
      return marker.length ? marker.map((l) => `▸ ${l.slice(3)}`).join('\n  ') : null;
    }
    default:
      return null;
  }
}

/**
 * Run the claude CLI with live output. `stream` uses stream-json so the agent's
 * tool calls become progress lines as they happen; otherwise stdout is captured
 * and only a heartbeat is shown. Either way the raw stream lands in `logPath`.
 */
function runClaude({ cliArgs, logPath, cwd, stream = false, label: tag = '', activity = 'working', timeoutMs = 0 }) {
  return new Promise((resolve, reject) => {
    const child = spawn('claude', cliArgs, { cwd: cwd ?? root, stdio: ['ignore', 'pipe', 'pipe'] });
    const began = Date.now();
    let out = '';
    let err = '';
    let pending = '';
    let events = 0;
    let lastPrint = Date.now();

    const say = (line) => {
      console.log(`  ${elapsed(began).padStart(5)}  ${tag ? `[${tag}] ` : ''}${line}`);
      lastPrint = Date.now();
    };
    // Without a heartbeat, a long think reads as a hang. Concurrent runs share
    // one console, so they tick far less often to stay readable.
    const quietFor = stream ? 20000 : 90000;
    const heartbeat = setInterval(() => {
      if (Date.now() - lastPrint > quietFor) say(`… still ${activity}`);
    }, 5000);
    // A single wedged generation must not hold the whole run hostage. The agent
    // spends nearly all of this blocked on the API, so the cap is wall-clock.
    const deadline = timeoutMs > 0 && setTimeout(() => {
      say(
        `✖ exceeded the ${Math.round(timeoutMs / 60000)}m cap — killing this generation ` +
        `(it may have been mid-write; raise --timeout if this repeats)`,
      );
      child.kill('SIGKILL');
    }, timeoutMs);

    child.stdout.on('data', (chunk) => {
      const text = chunk.toString();
      out += text;
      pending += text;
      const lines = pending.split('\n');
      pending = lines.pop() ?? '';
      for (const line of lines) {
        // Always count events so the summary stays truthful in quiet mode; only
        // print them when this run owns the console.
        for (const event of parseClaudeStreamLine(line)) {
          events += 1;
          if (!stream) continue;
          const rendered = progressLine(event);
          if (rendered) say(truncate(rendered));
        }
      }
    });
    const done = () => {
      clearInterval(heartbeat);
      if (deadline) clearTimeout(deadline);
    };
    child.stderr.on('data', (chunk) => { err += chunk.toString(); });
    child.on('error', (e) => { done(); reject(e); });
    child.on('close', (code) => {
      done();
      writeFileSync(logPath, `exit ${code}\n--- stdout ---\n${out}\n--- stderr ---\n${err}`);
      if (code !== 0) {
        // An exhausted API retry chain is an infrastructure blip, not a story
        // failure. Saying so keeps a flaky run from being read as a quality
        // regression and re-run as if the prompt had broken something.
        const infra = retriesExhausted(out);
        reject(new Error(
          infra
            ? `claude gave up after ${infra} API retries (${elapsed(began)}) — infrastructure, not a story failure; re-run this case. See ${logPath}`
            : `claude exited ${code} after ${elapsed(began)}; see ${logPath}`,
        ));
        return;
      }
      resolve({ out, events, took: elapsed(began) });
    });
  });
}

/**
 * Final text of a `muse exec --json` run. The authoritative answer is the
 * `run.terminal.*` event's text; concatenated `run.output.delta` texts are the
 * fallback when the run was killed before its terminal event.
 */
export function museFinalText(streamOutput) {
  let terminal = null;
  let deltas = '';
  let deltaCount = 0;
  for (const line of String(streamOutput).split('\n')) {
    if (!line.startsWith('{')) continue;
    let event;
    try {
      event = JSON.parse(line);
    } catch {
      continue;
    }
    if (event.payload_type === 'run.output.delta' && typeof event.payload?.text === 'string') {
      deltas += event.payload.text;
      deltaCount += 1;
    } else if (typeof event.payload_type === 'string' && event.payload_type.startsWith('run.terminal.')) {
      terminal = event.payload;
    }
  }
  if (!terminal) return { ok: false, text: deltas, reason: 'no terminal event', deltas: deltaCount };
  const ok = terminal.terminal === 'completed';
  return {
    ok,
    text: typeof terminal.text === 'string' && terminal.text ? terminal.text : deltas,
    reason: ok ? null : (terminal.reason ?? terminal.terminal ?? 'unknown'),
    deltas: deltaCount,
  };
}

/**
 * Run the muse CLI headless (`muse exec --json`). Same shape as runClaude —
 * heartbeat, wall-clock cap, full stream to the log — but `out` resolves to
 * the run's final text, which is what the judge parsers read.
 */
function runMuse({ prompt, logPath, cwd, label: tag = '', activity = 'working', timeoutMs = 0 }) {
  return new Promise((resolve, reject) => {
    const child = spawn('muse', [
      'exec', '--json',
      '--workspace', cwd,
      '--disable-approval',
      '--model', MUSE_MODEL,
      prompt,
    ], { cwd, stdio: ['ignore', 'pipe', 'pipe'] });
    const began = Date.now();
    let out = '';
    let err = '';
    let lastPrint = Date.now();

    const say = (line) => {
      console.log(`  ${elapsed(began).padStart(5)}  ${tag ? `[${tag}] ` : ''}${line}`);
      lastPrint = Date.now();
    };
    const heartbeat = setInterval(() => {
      if (Date.now() - lastPrint > 90000) say(`… still ${activity}`);
    }, 5000);
    const deadline = timeoutMs > 0 && setTimeout(() => {
      say(
        `✖ exceeded the ${Math.round(timeoutMs / 60000)}m cap — killing this generation ` +
        `(it may have been mid-write; raise --timeout if this repeats)`,
      );
      child.kill('SIGKILL');
    }, timeoutMs);

    child.stdout.on('data', (chunk) => { out += chunk.toString(); });
    const done = () => {
      clearInterval(heartbeat);
      if (deadline) clearTimeout(deadline);
    };
    child.stderr.on('data', (chunk) => { err += chunk.toString(); });
    child.on('error', (e) => { done(); reject(e); });
    child.on('close', (code) => {
      done();
      writeFileSync(logPath, `exit ${code}\n--- stdout ---\n${out}\n--- stderr ---\n${err}`);
      const final = museFinalText(out);
      if (code !== 0 || !final.ok) {
        const why = final.reason && final.reason !== 'no terminal event' ? ` (${final.reason})` : '';
        reject(new Error(`muse exited ${code} after ${elapsed(began)}${why}; see ${logPath}`));
        return;
      }
      resolve({ out: final.text, events: final.deltas, took: elapsed(began) });
    });
  });
}

/**
 * Recover a story stranded by an older harness version, which borrowed the live
 * `.codestory/story.json` during generation. Generation is fully isolated now,
 * but an interrupted run from before that change can still leave the backup
 * behind, and silently leaving the reviewer without their story is unacceptable.
 */
function recoverStrandedStory() {
  if (!existsSync(backupPath)) return;
  if (!existsSync(storyPath)) {
    renameSync(backupPath, storyPath);
    console.log('Recovered .codestory/story.json from an interrupted earlier run.');
    return;
  }
  rmSync(backupPath);
}

let interrupted = false;
for (const signal of ['SIGINT', 'SIGTERM']) {
  process.on(signal, () => {
    if (interrupted) process.exit(130);
    interrupted = true;
    console.log('\n\nInterrupted — cleaning up worktrees and stopping.');
    // Leave no worktrees behind; prune also clears any registration whose
    // directory removal loses the race with exit.
    try {
      rmSync(join(root, '.eval-worktrees'), { recursive: true, force: true });
      git('worktree', 'prune');
    } catch { /* best effort on the way out */ }
    process.exit(130);
  });
}

/**
 * Isolate one case in its own git worktree (or a --shared clone, for cases in
 * another repository). Each tree gets its own `.codestory/story.json`, so
 * generations never contend for the shared file and the live repo is never
 * mutated. Detached at the case head, so the files the agent reads are the
 * post-change files, as they are when an agent has just made the change.
 */
function makeWorktree(c) {
  const path = join(root, '.eval-worktrees', c.id);
  rmSync(path, { recursive: true, force: true });
  if (c.repo) {
    // Another repository: clone it (sharing its object store, read-only)
    // instead of adding a worktree, so the harness never writes into that
    // repo's .git. Detach at the case head so files on disk are post-change.
    gitIn(root, 'clone', '--quiet', '--shared', '--no-checkout', caseRepo(c), path);
    gitIn(path, 'checkout', '--quiet', '--detach', c.head);
    return {
      path,
      storyFile: join(path, '.codestory', 'story.json'),
      cleanup: () => rmSync(path, { recursive: true, force: true }),
    };
  }
  // A worktree killed mid-run stays registered in .git/worktrees even after its
  // directory is gone, and `worktree add` then refuses the path. Prune first so
  // an interrupted run never blocks the next one.
  git('worktree', 'prune');
  // Detached at the case head, so the files the agent reads are the
  // post-change files, as they are when an agent has just made the change.
  git('worktree', 'add', '--detach', '--quiet', path, c.head);
  return {
    path,
    storyFile: join(path, '.codestory', 'story.json'),
    cleanup: () => {
      try {
        git('worktree', 'remove', '--force', path);
      } catch {
        rmSync(path, { recursive: true, force: true });
      }
    },
  };
}

/**
 * Build every worktree before any agent starts. `git worktree` mutates shared
 * `.git` state, so creating them from concurrent workers would race on its lock.
 */
function makeWorktrees(caseList) {
  // SIGKILL, a crashed parent, or a closed terminal skips the signal handlers,
  // so worktrees from an earlier run can still be on disk — including ones for
  // cases this run does not touch. Sweep the whole directory before starting.
  rmSync(join(root, '.eval-worktrees'), { recursive: true, force: true });
  git('worktree', 'prune');
  const trees = new Map();
  for (const c of caseList) trees.set(c.id, makeWorktree(c));
  return trees;
}

/**
 * Generate one story. Always runs in an isolated worktree — never in the live
 * repo. Borrowing the repo's own `.codestory/story.json` used to be the
 * single-case path, and it silently broke anything else touching the repo
 * mid-run (the app-server tests read that file and fail while it is moved away).
 * Isolation costs one cheap worktree and makes a run safe to leave unattended.
 */
async function generate(c, { worktree, quiet = false } = {}) {
  const caseDir = join(outDir, c.id);
  mkdirSync(caseDir, { recursive: true });
  const tree = worktree;
  const evolutionManifest = commitEvolutionManifest(tree.path, c.base, c.head);
  const prompt = storyPrompt(c.base, c.head, c.mode, c.excludePaths ?? [], undefined, evolutionManifest);
  writeFileSync(join(caseDir, 'prompt.txt'), prompt);
  console.log(
    `\n▶ generate ${c.id} (${c.mode}, model ${genLabel})` +
    (quiet ? ' — running in parallel, output on completion' : ' — live agent progress below'),
  );
  // Reuse the app's own stream-json invocation so eval runs see exactly what
  // the review UI would show while a story is being written.
  const [, cliArgs] = streamCommand('claude', prompt, genModel);
  const runOpts = {
    cwd: tree.path,
    logPath: join(caseDir, 'generate.log'),
    label: quiet ? c.id : '',
    activity: 'writing the story',
    // A case may declare its own cap when it is known to be thinking-bound.
    timeoutMs: c.timeoutMinutes ? c.timeoutMinutes * 60000 : timeoutMs,
  };
  const { events, took } = runner === 'muse'
    ? await runMuse({ prompt, ...runOpts })
    : await runClaude({ cliArgs, stream: !quiet, ...runOpts });
  if (!existsSync(tree.storyFile)) throw new Error(`agent finished but wrote no ${tree.storyFile}`);
  const normalized = JSON.parse(readFileSync(tree.storyFile, 'utf8'));
  normalizeEvolutionObject(normalized, evolutionManifest);
  writeFileSync(tree.storyFile, `${JSON.stringify(normalized, null, 2)}\n`);
  copyFileSync(tree.storyFile, join(caseDir, 'story.json'));
  console.log(`  ✓ ${c.id} captured in ${took} (${events} agent events) -> eval/results/${label}/${c.id}/story.json`);
}

/**
 * Every authored prose field, as [path, text] pairs. Mirrors what validateTour
 * checks, so the two cannot drift about what counts as narrative.
 */
function narrativeFields(tour) {
  const out = [];
  const add = (path, value) => { if (typeof value === 'string' && value.trim()) out.push([path, value]); };
  add('title', tour.title);
  add('summary', tour.summary);
  add('intent.goal', tour.intent?.goal);
  add('intent.design', tour.intent?.design);
  add('storyArc.readingPath', tour.storyArc?.readingPath);
  (tour.intent?.nonGoals ?? []).forEach((g, i) => add(`intent.nonGoals[${i}]`, g));
  (tour.evolution?.phases ?? []).forEach((p, i) => {
    add(`evolution.phases[${i}].title`, p.title);
    add(`evolution.phases[${i}].summary`, p.summary);
  });
  (tour.hotspots ?? []).forEach((h, i) => add(`hotspots[${i}].reason`, h.reason));
  (tour.steps ?? []).forEach((s, i) => {
    add(`steps[${i}].title`, s.title);
    add(`steps[${i}].why`, s.why);
    add(`steps[${i}].body`, s.body);
    add(`steps[${i}].narration`, s.narration);
    add(`steps[${i}].diagram.caption`, s.diagram?.caption);
    (s.beats ?? []).forEach((b, j) => add(`steps[${i}].beats[${j}].text`, b.text));
  });
  return out;
}

/**
 * Markdown written into a field that is now HTML. This is the one narrative
 * failure `validateTour` cannot catch: there is no illegal tag to reject, so the
 * story validates clean and then renders `**bold**` as four literal characters
 * in front of the reviewer. Without this the eval scores a format regression as
 * a perfect run.
 */
function markdownResidue(tour) {
  const hits = [];
  for (const [path, text] of narrativeFields(tour)) {
    for (const [pattern, label] of MARKDOWN_RESIDUE) {
      if (pattern.test(text)) { hits.push(`${path}: ${label}`); break; }
    }
  }
  return hits;
}

/** Which of the new affordances the story actually reached for. Informative, not a gate. */
function markupUse(tour) {
  const all = narrativeFields(tour).map(([, text]) => text).join('\n');
  const count = (re) => (all.match(re) ?? []).length;
  return {
    tables: count(/<table[\s>]/g),
    definitionLists: count(/<dl[\s>]/g),
    inlineCode: count(/<code[\s>]/g),
    signalSpans: count(/class=["'](?:ds-bit|ds-slot|ds-flag|ds-val|ds-warn)["']/g),
  };
}

/** Post-change lines of a case file, read from the case repo at `head` (cached). */
function caseLines(c) {
  const cache = new Map();
  return (file) => {
    if (!cache.has(file)) {
      try {
        cache.set(file, gitIn(caseRepo(c), 'show', `${c.head}:${file}`).split('\n'));
      } catch {
        cache.set(file, null);
      }
    }
    return cache.get(file);
  };
}

/** Lint findings folded into counts: the eval tracks rules, not every place. */
export function summarizeLint(findings) {
  const byRule = {};
  for (const f of findings) byRule[f.rule] = (byRule[f.rule] ?? 0) + 1;
  return {
    errors: findings.filter((f) => f.severity === 'error').length,
    warnings: findings.filter((f) => f.severity === 'warning').length,
    byRule,
  };
}

// Mechanical scores are free and objective: the app's own gates.
function mechanicalScores(c, tour) {
  const files = parseUnifiedDiff(caseDiff(c));
  const uncovered = computeCoverage(tour, filesForStoryCoverage(tour, files)).uncovered;
  const codeSteps = tour.steps.filter((s) => s.kind !== 'concept');
  // Mirror the app: loadTour() runs validateTour() and refuses a malformed story
  // before the stricter generated profile ever sees it. Running the strict pass
  // on a story that already failed the basic shape yields noise, not signal.
  const validationErrors = validateTour(tour);
  return {
    validationErrors,
    generatedProfileErrors: validationErrors.length
      ? ['(skipped: story failed basic validation)']
      : validateNewGeneratedStory(tour),
    uncoveredHunks: uncovered.length,
    // A story written in the old format validates clean and then renders its
    // asterisks literally, so this is tracked separately from validationErrors.
    markdownResidue: markdownResidue(tour),
    // Deterministic craft lints (src/story-lint.ts); skipped when the story
    // failed basic validation, like the generated profile above.
    lint: validationErrors.length ? null : summarizeLint(lintStory(tour, { readLines: caseLines(c) })),
    markupUse: markupUse(tour),
    steps: tour.steps.length,
    conceptSteps: tour.steps.length - codeSteps.length,
    hotspots: tour.hotspots?.length ?? 0,
    nonGoals: tour.intent?.nonGoals?.length ?? 0,
    avgViewportLines: codeSteps.length
      ? Math.round(
          codeSteps.reduce((a, s) => a + (s.viewport ? s.viewport[1] - s.viewport[0] + 1 : 0), 0) / codeSteps.length,
        )
      : 0,
  };
}

